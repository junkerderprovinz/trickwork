// Writes ui/src/glyphs.ts from GlimStone's glyphs.json, copied to
// ui/src/design/, keeping only the glyphs TrickWork wears. Run it after
// copying a newer glyphs.json or adding a name below:
//
//   node scripts/gen-glyphs.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const USED = [
  'IconBack',
  'IconCornerLeaf',
  'IconCornerRound',
  'IconCornerSoft',
  'IconCornerSquare',
  'IconDiagnostics',
  'IconDownload',
  'IconExternalLink',
  'IconGear',
  'IconGrip',
  'IconInfo',
  'IconMoon',
  'IconMotionOff',
  'IconMotionStorm',
  'IconMotionSubtle',
  'IconMotionWild',
  'IconSun',
  'IconTabApp',
  'IconTabGeneral',
  'IconTabLook',
  'IconThemeSystem',
  'IconUpload',
]

const root = new URL('../ui/src/', import.meta.url)
const all = JSON.parse(readFileSync(new URL('design/glyphs.json', root), 'utf8'))

const entries = USED.map((name) => {
  const glyph = all.find((g) => g.name === name)
  if (!glyph) throw new Error(`gen-glyphs: ${name} is not in glyphs.json`)
  const body = glyph.svg.replace(/>\s+</g, '><').trim()
  return `export const ${name}: Glyph = {\n  viewBox: '${glyph.viewBox}',\n  body: '${body.replace(/'/g, "\\'")}',\n}\n`
})

const out = `// Generated by scripts/gen-glyphs.mjs from design/glyphs.json, GlimStone's
// glyph assortment. Do not edit by hand. The drawings come from Streamline's
// free Core Solid (CC BY 4.0, https://streamlinehq.com), Font Awesome Free
// (CC BY 4.0) and Material Design Icons (Apache 2.0), or were drawn for
// GlimStone and its apps.

export interface Glyph {
  viewBox: string
  body: string
}

${entries.join('\n')}`

writeFileSync(fileURLToPath(new URL('glyphs.ts', root)), out)
